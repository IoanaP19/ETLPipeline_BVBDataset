"""
main.py — BVB ETL Pipeline Orchestrator
========================================
Bachelor Thesis: "An Applied Perspective on ETL: Python-Based Use Cases
                  for Business Analytics"

How to run:
    python main.py                  — run the full ETL pipeline
    streamlit run dashboard.py      — launch the interactive BI dashboard

Pipeline steps:
    1. extract   → downloads BVB prices from Yahoo Finance (2024–2025)
    2. transform → cleans data; computes returns, SMA, drawdown, volatility
    3. load      → saves to outputs/bvb_warehouse.db (SQLite) + CSV
    4. analyse   → computes summary tables; writes timestamped Excel report

Visualisation is fully decoupled: dashboard.py queries bvb_warehouse.db
directly. No static PNG charts are generated by this pipeline.

All output (console + log file) is handled by the logging module.
See outputs/pipeline.log for the complete run trace.
"""

import json
import sys
import time
from pathlib import Path

from src.logger import get_logger
import src.extract   as extract
import src.transform as transform
import src.load      as load
import src.analyse   as analyse

log = get_logger(__name__)

CONFIG_PATH = Path(__file__).parent / "config.json"


def load_config() -> dict:
    """Read and return the configuration from config.json."""
    if not CONFIG_PATH.exists():
        log.error(f"config.json not found at {CONFIG_PATH}")
        sys.exit(1)
    with CONFIG_PATH.open(encoding="utf-8") as f:
        cfg = json.load(f)
    log.info(f"Configuration loaded from {CONFIG_PATH.name}")
    return cfg


def main() -> None:
    t0  = time.perf_counter()
    cfg = load_config()

    log.info("╔══════════════════════════════════════════════════════╗")
    log.info("║          BVB ETL PIPELINE — starting                 ║")
    log.info("╚══════════════════════════════════════════════════════╝")

    # ── Step 1: Extract ───────────────────────────────────────────────────────
    df_raw = extract.run(cfg)

    # ── Step 2: Transform ─────────────────────────────────────────────────────
    # Returns a tuple: (df_final, df_quarantine)
    # df_final      — clean rows, |daily_return| ≤ 15%
    # df_quarantine — flagged rows, 15% < |daily_return| ≤ 25%, pending review
    df_final, df_quarantine = transform.run(df_raw, cfg)

    # ── Step 3: Load ──────────────────────────────────────────────────────────
    # df_final      → market_data      (analytics-ready, used by dashboard)
    # df_quarantine → data_audit_log   (pending human review in dashboard)
    db_path, csv_path = load.run(df_final, df_quarantine, cfg)

    # ── Step 4: Analyse + Report ───────────────────────────────────────────────
    # Analytics run only on df_final — vetted, clean data.
    # Quarantined rows are excluded until a human approves them in the dashboard.
    results = analyse.run(df_final, cfg)

    # ── Summary ───────────────────────────────────────────────────────────────
    elapsed = time.perf_counter() - t0
    log.info("╔══════════════════════════════════════════════════════╗")
    log.info("║          BVB ETL PIPELINE — complete                 ║")
    log.info(f"║  Duration   : {elapsed:>6.1f}s                              ║")
    log.info(f"║  Rows saved : {len(df_final):>6,}                              ║")
    log.info(f"║  Tickers    : {df_final['ticker'].nunique():>6}                              ║")
    log.info("║                                                      ║")
    log.info("║  Outputs:                                            ║")
    log.info("║    bvb_warehouse.db        ← Streamlit reads this    ║")
    log.info("║    bvb_processed.csv       ← full dataset as CSV     ║")
    log.info("║    bvb_etl_report_*.xlsx   ← summary tables          ║")
    log.info("║    pipeline.log            ← full run trace          ║")
    log.info("╚══════════════════════════════════════════════════════╝")
    log.info("Next step: streamlit run dashboard.py")


if __name__ == "__main__":
    main()
